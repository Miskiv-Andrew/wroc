    def _ser_num_data(self, data: bytearray) -> str | None:
        """
        Извлекает серийный номер прибора из ответа SER_NUM.

        Серийный номер хранится в BCD-формате.

        Для корректного BCD каждый используемый полубайт
        должен находиться в диапазоне 0..9.

        Возвращает:
            str  - корректный серийный номер;
            None - если данные серийного номера повреждены.
        """

        # ============================================================
        # 1. ПРОВЕРЯЕМ МИНИМАЛЬНУЮ ДЛИНУ ПАКЕТА
        # ============================================================
        #
        # Для получения серийного номера используются байты:
        #
        #     data[5]
        #     data[6]
        #     data[7]
        #     data[8]
        #
        # Поэтому пакет должен содержать как минимум 9 байт.

        if data is None or len(data) < 9:
            return None

        # ============================================================
        # 2. ИЗВЛЕКАЕМ BCD-ЦИФРЫ
        # ============================================================
        #
        # Формат, используемый существующим протоколом:
        #
        #     младший полубайт data[8],
        #     затем data[7] HIGH / LOW,
        #     затем data[6] HIGH / LOW,
        #     затем data[5] HIGH / LOW.
        #
        # В результате получаем семизначный серийный номер.

        digits = []

        # Первая цифра серийного номера.
        digits.append(
            data[8] & 0x0F
        )

        # Остальные шесть цифр.
        for i in range(7, 4, -1):

            high_nibble = (
                data[i] >> 4
            ) & 0x0F

            low_nibble = (
                data[i]
            ) & 0x0F

            digits.append(
                high_nibble
            )

            digits.append(
                low_nibble
            )

        # ============================================================
        # 3. ПРОВЕРЯЕМ КОРРЕКТНОСТЬ BCD
        # ============================================================
        #
        # Допустимы только значения 0..9.
        #
        # Значения:
        #
        #     A, B, C, D, E, F
        #
        # не являются десятичными цифрами и означают,
        # что содержимое SER_NUM нельзя считать корректным.

        for digit in digits:

            if digit < 0 or digit > 9:
                return None

        # ============================================================
        # 4. ФОРМИРУЕМ СТРОКУ СЕРИЙНОГО НОМЕРА
        # ============================================================

        serial_number = "".join(
            str(digit)
            for digit in digits
        )

        return serial_number


    def _temp_data(self, data: bytearray, b1: int = 0) -> str | None:
        """       
            Возвращает строку с значением температуры
        """
        
        # Проверка валидности
        if data[6+b1] & 0x80:
            return None

        # Собираем слово из двух байтов
        temp_w = (data[5+b1]) | (data[6+b1] << 8)

        # Проверка знака
        if data[6+b1] & 0x10:
            temp_w = (~temp_w) & 0xFFF
            temp_w += 1
            sign = "-"
        else:
            sign = ""

        # Берём младшие 12 бит и делим на 16
        temp_r = (temp_w & 0xFFF) / 16.0
        return f"{sign}{temp_r:.1f}"
    

    def _rad_intens_data(self, data: bytearray) -> int:
        """
            Функция получает интенсивность излучения (CPS) за 100 мсек
            Возвращает INT значение интенсивности
        """
        byte5 = data[5]
        byte6 = data[6]        
        
        Intense = struct.unpack('<H', bytes([byte5, byte6]))[0]        
        
        return Intense
    
    def _paed_data(self, data: bytearray) -> dict:
        """
            Обработка данных ПАЕД
            Возвращает словарь с параметрами 
        """
        num = struct.unpack('<I', data[5:9])[0]
        accuracy = data[9]  # 9th byte from the packet payload
        ped = 0
        
        byte_to_check = data[10]
        
        high_sens_detect_failure = True
        low_sens_detector_failure = True
        result_valid = True        
        
        if byte_to_check & 0b00000001:   # D0 = 1 - отказ высокочувствительного детектора
            high_sens_detect_failure = False     
        
        if byte_to_check & 0b00000010:   # D1 = 1 - отказ низкочувствительного детектора
            low_sens_detector_failure = False  
        
        if byte_to_check & 0b00000100:   # D2 = 1 - результат невалидный
            result_valid = False         

            
        if byte_to_check & 0b10000000:   # Коэффициент перерасчета ПЕД 
            ped = num * 0.1        
        else:
            ped = num * 0.01 
        
        return {
            "ped_value": ped,
            "accuracy": accuracy,
            "high_sens_failure": high_sens_detect_failure,
            "low_sens_failure": low_sens_detector_failure,
            "result_valid": result_valid
        }
    


    def _parse_spectrum_data(self, data: bytearray) -> dict:
        """
        Парсинг ответа GET_SIMPLE_SPECTRE (2076 байт)
        Возвращает словарь:
            - channels: list[int] - 1024 канала спектра (little-endian, 2 байта на канал)
            - paed_value: float - значение ПАЕД из байт 2056-2059
            - test_byte: int - байт 2061 (статус детекторов и валидности)
            - valid: bool - флаг валидности (D2 из test_byte)
        """
        # 1. Массив спектра: 1024 канала * 2 байта = 2048 байт, начиная с байта 6
        channels = []
        for i in range(1023):
            # little-endian: младший байт первый
            low_byte = data[6 + i * 2]
            high_byte = data[6 + i * 2 + 1]
            value = (high_byte << 8) | low_byte
            channels.append(value)

        # 2. Час набора спектра (байти 2054-2055, little-endian)
        acq_time = struct.unpack('<H', data[2054:2056])[0]

        channels.append(acq_time)
        
        # 3. ПАЕД из байт 2056-2059 (4 байта, little-endian unsigned int)
        paed_raw = struct.unpack('<I', data[2056:2060])[0]
        # Пересчёт ПАЕД по коэффициенту (аналогично _paed_data)
        paed_value = paed_raw * 0.1 if (data[2061] & 0x80) else paed_raw * 0.01
        
        accuracy = data[2060]

        # 4. Тестовый байт (байт 2061)
        test_byte = data[2061]
        
        # 5. Валидность результата (D2 = 1 - невалидный, D2 = 0 - валидный)
        # В _paed_data: result_valid = True (валидный) если бит НЕ установлен
        result_valid = not (test_byte & 0b00000100)
        
        return {
            "channels": channels,
            "paed_value": paed_value,
            "accuracy": accuracy,
            "test_byte": test_byte,
            "valid": result_valid            
        }

