    def _ser_num_data(self, data: bytearray) -> str | None:
        """
        Извлекает серийный номер прибора из ответа SER_NUM.

        Серийный номер хранится в BCD-формате.

        Для корректного BCD каждый используемый полубайт
        должен находиться в диапазоне 0..9.

        Возвращает:
            str  - корректный серийный номер;
            None - если данные серийного номера повреждены.
        """

        # ============================================================
        # 1. ПРОВЕРЯЕМ МИНИМАЛЬНУЮ ДЛИНУ ПАКЕТА
        # ============================================================
        #
        # Для получения серийного номера используются байты:
        #
        #     data[5]
        #     data[6]
        #     data[7]
        #     data[8]
        #
        # Поэтому пакет должен содержать как минимум 9 байт.

        if data is None or len(data) < 9:
            return None

        # ============================================================
        # 2. ИЗВЛЕКАЕМ BCD-ЦИФРЫ
        # ============================================================
        #
        # Формат, используемый существующим протоколом:
        #
        #     младший полубайт data[8],
        #     затем data[7] HIGH / LOW,
        #     затем data[6] HIGH / LOW,
        #     затем data[5] HIGH / LOW.
        #
        # В результате получаем семизначный серийный номер.

        digits = []

        # Первая цифра серийного номера.
        digits.append(
            data[8] & 0x0F
        )

        # Остальные шесть цифр.
        for i in range(7, 4, -1):

            high_nibble = (
                data[i] >> 4
            ) & 0x0F

            low_nibble = (
                data[i]
            ) & 0x0F

            digits.append(
                high_nibble
            )

            digits.append(
                low_nibble
            )

        # ============================================================
        # 3. ПРОВЕРЯЕМ КОРРЕКТНОСТЬ BCD
        # ============================================================
        #
        # Допустимы только значения 0..9.
        #
        # Значения:
        #
        #     A, B, C, D, E, F
        #
        # не являются десятичными цифрами и означают,
        # что содержимое SER_NUM нельзя считать корректным.

        for digit in digits:

            if digit < 0 or digit > 9:
                return None

        # ============================================================
        # 4. ФОРМИРУЕМ СТРОКУ СЕРИЙНОГО НОМЕРА
        # ============================================================

        serial_number = "".join(
            str(digit)
            for digit in digits
        )

        return serial_number
    


    def _temp_data(self, data: bytearray, b1: int = 0) -> str | None:
        """
        Декодирует температуру из ответа БДБГ-09.

        Возвращает:
            строку температуры с точностью до 0.1 °C,
            например:
                "23.5"
                "-10.0"

            None:
                если пакет недостаточной длины
                или термодатчик сообщил об отказе.

        Формат температурных данных БДБГ-09:

            младший байт:
                D7..D4 -> 2^3 .. 2^0
                D3..D0 -> 2^-1 .. 2^-4

            старший байт:
                D2..D0 -> 2^6 .. 2^4
                D4      -> S:
                        0 - положительная температура
                        1 - отрицательная температура

                D7      -> состояние термодатчика:
                        0 - норма
                        1 - отказ

        ВАЖНО:
            знак температуры передаётся отдельным битом S.
            Температура НЕ представлена в дополнительном коде.
        """

        # ============================================================
        # 1. ПРОВЕРЯЕМ СМЕЩЕНИЕ
        # ============================================================

        if b1 < 0:
            return None

        # ============================================================
        # 2. ПРОВЕРЯЕМ, ЧТО НУЖНЫЕ БАЙТЫ СУЩЕСТВУЮТ
        # ============================================================
        #
        # Для декодирования температуры используются:
        #
        #     data[5 + b1]
        #     data[6 + b1]
        #
        # Поэтому последний необходимый индекс обязан существовать.

        required_index = 6 + b1

        if data is None or len(data) <= required_index:
            return None

        # ============================================================
        # 3. ПОЛУЧАЕМ БАЙТЫ ТЕМПЕРАТУРЫ
        # ============================================================

        temp_low = data[5 + b1]
        temp_high = data[6 + b1]

        # ============================================================
        # 4. ПРОВЕРЯЕМ СОСТОЯНИЕ ТЕРМОДАТЧИКА
        # ============================================================
        #
        # D7 старшего байта:
        #
        #     0 - термодатчик исправен
        #     1 - отказ термодатчика

        if temp_high & 0x80:
            return None

        # ============================================================
        # 5. ОПРЕДЕЛЯЕМ ЗНАК
        # ============================================================
        #
        # D4 является отдельным битом знака S:
        #
        #     S = 0 -> температура положительная
        #     S = 1 -> температура отрицательная
        #
        # Это НЕ дополнительный код.

        is_negative = bool(
            temp_high & 0x10
        )

        # ============================================================
        # 6. СОБИРАЕМ МОДУЛЬ ТЕМПЕРАТУРЫ
        # ============================================================
        #
        # В старшем байте для значения температуры используются
        # только D2..D0.
        #
        # D7 - отказ датчика.
        # D4 - знак.
        #
        # Поэтому служебные биты необходимо исключить.

        temperature_raw = (
            ((temp_high & 0x07) << 8)
            | temp_low
        )

        # ============================================================
        # 7. ПЕРЕВОДИМ В ГРАДУСЫ ЦЕЛЬСИЯ
        # ============================================================
        #
        # Четыре младших разряда являются дробной частью:
        #
        #     2^-1
        #     2^-2
        #     2^-3
        #     2^-4
        #
        # Поэтому цена младшего разряда = 1 / 16 °C.

        temperature = (
            temperature_raw / 16.0
        )

        # ============================================================
        # 8. ПРИМЕНЯЕМ ЗНАК
        # ============================================================

        if is_negative:
            temperature = -temperature

        # ============================================================
        # 9. ВОЗВРАЩАЕМ ЗНАЧЕНИЕ
        # ============================================================

        return f"{temperature:.1f}"    
    

    def _rad_intens_data(self, data: bytearray) -> int:
        """
            Функция получает интенсивность излучения (CPS) за 100 мсек
            Возвращает INT значение интенсивности
        """
        byte5 = data[5]
        byte6 = data[6]        
        
        Intense = struct.unpack('<H', bytes([byte5, byte6]))[0]        
        
